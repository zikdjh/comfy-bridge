"""nodes.lock.yaml 读写与生成（M2-2 镜像固化的锁文件与依赖预装脚本）。

- 锁文件来源 = 本地扫描（权威）：只收「启用且有 requirements.txt」的目录型节点包，
  requirements 去注释去空行后逐条登记；ComfyUI 版本取版本 pin（version_align.read_pin）。
- 格式：JSON 文本（JSON 是 YAML 1.2 的子集，.yaml 后缀合法，工具可直接读）——
  避免为后端显式引入 pyyaml 依赖。
- install_nodes.sh 由锁文件渲染，runner.py 镜像构建时 add_local_file + 执行，
  依赖预装进镜像；冷启动的按节点 pip 安装降级为兜底（覆盖卷模式新装、未固化的节点）。
- 重建失败回滚：backup_and_write 返回旧内容，调用方在 deploy 失败时 restore。
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from . import version_align
from .scan import scan_custom_nodes

LOCK_FILE = version_align.REPO_ROOT / "modal-runner" / "lock" / "nodes.lock.yaml"
SCRIPT_FILE = version_align.REPO_ROOT / "modal-runner" / "lock" / "install_nodes.sh"


def parse_requirements(text: str) -> list[str]:
    """requirements.txt → 有效依赖行：去整行注释/空行与行尾注释，保留环境标记。

    行尾注释仅在 " #"（井号前有空白）时剥离，避免误伤 URL 片段（git+https://…#egg=x）。
    """
    out: list[str] = []
    for line in (text or "").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        marker = line.find(" #")
        if marker != -1:
            line = line[:marker].strip()
        if line:
            out.append(line)
    return out


def generate(scan: dict | None = None) -> dict:
    """本地扫描 → 锁文件 dict；仅启用且有 requirements 的包（单文件节点无依赖不收）。"""
    scan = scan or scan_custom_nodes()
    nodes = []
    for p in scan.get("packages", []):
        if not p.get("enabled") or not p.get("has_requirements"):
            continue
        req_path = Path(scan["path"]) / p["name"] / "requirements.txt"
        try:
            reqs = parse_requirements(req_path.read_text(encoding="utf-8"))
        except OSError:
            continue
        nodes.append({
            "name": p["name"],
            "repo": p.get("repo"),
            "commit": p.get("commit"),
            "requirements": reqs,
        })
    nodes.sort(key=lambda n: n["name"])
    return {
        "schema": 1,
        "generated_at": datetime.now(UTC).isoformat(),
        "comfyui_version": version_align.read_pin(),
        "nodes": nodes,
    }


def read_lock() -> dict | None:
    try:
        data = json.loads(LOCK_FILE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def _dump(lock: dict) -> str:
    return json.dumps(lock, ensure_ascii=False, indent=2) + "\n"


def render_install_script(lock: dict) -> str:
    """锁文件 → install_nodes.sh：逐节点一组 pip install，set -e 严格失败（失败即整次构建失败）。"""
    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by ComfyBridge M2-2（nodes.lock.yaml → 依赖预装）。手改会被下次重建覆盖。",
        "set -e",
        "",
    ]
    nodes = [n for n in lock.get("nodes", []) if n.get("requirements")]
    if not nodes:
        lines += ['echo "[comfybridge] lock: 无需预装的节点依赖"', ""]
        return "\n".join(lines)
    for n in nodes:
        lines.append(f'echo "[comfybridge] install deps: {n["name"]}"')
        reqs = " ".join(f'"{r}"' for r in n["requirements"])
        lines.append(f"python -m pip install --no-cache-dir {reqs}")
        lines.append("")
    return "\n".join(lines)


def write_outputs(lock: dict, script: str) -> None:
    LOCK_FILE.parent.mkdir(parents=True, exist_ok=True)
    LOCK_FILE.write_text(_dump(lock), encoding="utf-8")
    SCRIPT_FILE.write_text(script, encoding="utf-8")


def backup_current() -> tuple[str | None, str | None]:
    """读取当前锁/脚本内容用于失败回滚。"""
    lock_text = script_text = None
    try:
        lock_text = LOCK_FILE.read_text(encoding="utf-8")
    except OSError:
        pass
    try:
        script_text = SCRIPT_FILE.read_text(encoding="utf-8")
    except OSError:
        pass
    return lock_text, script_text


def restore(lock_text: str | None, script_text: str | None) -> None:
    """deploy 失败后恢复旧内容；此前不存在则删掉新建文件，回到重建前状态。"""
    if lock_text is None:
        LOCK_FILE.unlink(missing_ok=True)
    else:
        LOCK_FILE.write_text(lock_text, encoding="utf-8")
    if script_text is None:
        SCRIPT_FILE.unlink(missing_ok=True)
    else:
        SCRIPT_FILE.write_text(script_text, encoding="utf-8")
